/** 별칭 → bookId 조회표. 긴 별칭이 먼저 매칭되도록 길이 내림차순. */
export function buildAliasIndex() {
  const entries = [];
  for (const [id, aliases] of Object.entries(BOOK_ALIASES)) {
    for (const a of aliases) entries.push({ alias: a, id });
  }
  entries.sort((x, y) => y.alias.length - x.alias.length);
  return entries;
}

export function bookName(id) {
  return BOOK_NAMES[id] || (BOOK_ALIASES[id] ? BOOK_ALIASES[id][0] : id);
}
